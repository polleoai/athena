"""Slug derivation policy + enforcement.

Every category in the vault has a different policy for how to derive the
filename slug from a captured source:

  * Social posts (X, LinkedIn, Substack threads): URL is the only stable
    identifier — the post title is often "Post | LinkedIn" (generic) or
    the first 30 chars of the body (changes on edit). MUST derive from URL.

  * Repos (GitHub): URL contains owner/repo which is canonical. MUST
    derive from URL — title-derived slugs collide ("readme" → already
    used by 14 other repos).

  * Webpages (general): URL contains host/path which is canonical.
    MUST derive from URL.

  * Papers (arXiv, journal PDFs): URL contains arxiv ID or DOI which
    IS canonical, but title is also stable. URL_DERIVED preferred,
    TITLE_DERIVED allowed as fallback when URL is a generic file://
    or PDF upload with no canonical URL.

  * Books: title is the canonical identifier (no URL exists for many
    books we ingest). TITLE_DERIVED required.

  * Videos (YouTube): URL contains video ID which is canonical.
    URL_DERIVED required.

The bug pattern this prevents: collision-bait slugs like `post-linkedin`,
`untitled`, `tweet`, `readme` — generated by title-derived logic on
generic-titled pages — which then alias-collapse multiple distinct
sources onto the same raw filename. Lint #39 was a band-aid that
auto-renamed these post-hoc; this enforces the rule at write time.

Pure functions, no I/O. Replaces the ad-hoc slug logic in:
  * bin/kb shell (clipper SLUG= sed pipeline)
  * bin/kb-capture:url_to_slug (shell function)
  * bin/lib/wiki_schema.py:_url_to_slug_input (URL → slug input)
  * bin/lib/ingest_file.py:_make_slug (file-based)

Phase 1 of the schema refactor: defines the contract. Phase 3 migrates
each call site. Phase 4 makes violations fail at write time.
"""

from __future__ import annotations

import re
import urllib.parse
from enum import Enum

from url_canonical import SourceKind, canonicalize, source_kind


class SlugPolicy(str, Enum):
    """How a slug is derived for a given category.

    URL_DERIVED: slug comes from canonical URL only. Title is ignored.
    TITLE_DERIVED: slug comes from title. URL is ignored.
    URL_PREFERRED: try URL first; fall back to title if URL is missing
        or unhelpful (file://, generic upload host).
    """

    URL_DERIVED = "url_derived"
    TITLE_DERIVED = "title_derived"
    URL_PREFERRED = "url_preferred"


# ─── Per-category policy ─────────────────────────────────────────────


_POLICY_BY_CATEGORY: dict[str, SlugPolicy] = {
    "papers": SlugPolicy.URL_PREFERRED,  # arxiv URL preferred, title fallback
    "repos": SlugPolicy.URL_DERIVED,
    "webpages": SlugPolicy.URL_DERIVED,
    "videos": SlugPolicy.URL_DERIVED,
    "images": SlugPolicy.URL_PREFERRED,
    "books": SlugPolicy.TITLE_DERIVED,
}


def policy_for(category: str) -> SlugPolicy:
    """Return the slug-derivation policy for a category. Defaults to
    URL_DERIVED — the safest default for any unknown category since it
    avoids collision-bait."""
    return _POLICY_BY_CATEGORY.get(category, SlugPolicy.URL_DERIVED)


# ─── Slug normalization ──────────────────────────────────────────────


_SLUG_MAX_LEN = 80


def _normalize(text: str, max_len: int = _SLUG_MAX_LEN) -> str:
    """Lowercase, replace non-alnum with '-', collapse, strip, truncate.

    This logic mirrors wiki_schema.make_slug — the canonical slug
    normalization. Once Phase 3 migrates wiki_schema callers, that
    function will delegate here.
    """
    if not text:
        return ""
    s = text.lower()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    s = re.sub(r"-{2,}", "-", s)
    s = s.strip("-.")
    if len(s) > max_len:
        s = s[:max_len].rstrip("-.")
    return s


def _slug_from_url(url: str) -> str:
    """Convert a canonical URL into a slug input.

    For social posts, includes the status ID (the only unique part).
    For repos, includes owner/repo. For papers, the arxiv ID.

    Returns the normalized slug, or "" if the URL is unusable (file://,
    no path, etc.).
    """
    if not url:
        return ""
    canon = canonicalize(url).url
    try:
        p = urllib.parse.urlparse(canon)
    except Exception:
        return ""
    if not p.netloc:
        return ""
    # Generic upload hosts (drive.google.com/file/d/<opaque-id>/view) need
    # special handling — the random ID alone isn't human-readable. Include
    # host+path for context.
    host = p.netloc
    path = p.path.rstrip("/")
    raw_input = f"{host}{path}".replace("/", "-")
    return _normalize(raw_input)


def _slug_from_title(title: str) -> str:
    """Convert a title into a slug. Rejects titles in the
    'collision-bait' set even if asked — these always produce duplicates."""
    if not title:
        return ""
    candidate = _normalize(title)
    if candidate in _COLLISION_BAIT_SLUGS:
        return ""
    return candidate


# Slugs that have proven to collide repeatedly in this vault (lint #39
# whitelist, generalized). Title-derived slug attempts that match these
# are rejected — caller must use URL-derived path instead.
_COLLISION_BAIT_SLUGS = frozenset({
    "post-linkedin",
    "untitled",
    "untitled-page",
    "tweet",
    "readme",
    "page",
    "post",
    "index",
    "home",
    "404",
    "error",
    "not-found",
})


# ─── Public API ──────────────────────────────────────────────────────


class SlugDerivationError(ValueError):
    """Raised when no valid slug can be derived under the given policy.

    Catch this in writers to either reject the write or fall back to a
    different capture path (e.g., re-fetch with a canonical URL)."""


def derive_slug(category: str, url: str | None, title: str | None) -> str:
    """Derive the canonical slug for a (category, url, title) triple.

    Applies the per-category policy. Raises SlugDerivationError if the
    policy demands a URL but URL is missing/unusable, or if the title
    is collision-bait under TITLE_DERIVED policy.

    Examples:
        >>> derive_slug("repos", "https://github.com/anthropics/skills", None)
        'github-com-anthropics-skills'
        >>> derive_slug("webpages",
        ...     "https://x.com/regent0x_/status/2049499354323399002?s=12",
        ...     "Tweet")
        'x-com-regent0x-status-2049499354323399002'
        >>> derive_slug("books", None, "Introduction to Measure Theory")
        'introduction-to-measure-theory'
    """
    policy = policy_for(category)

    if policy == SlugPolicy.URL_DERIVED:
        slug = _slug_from_url(url or "")
        if not slug:
            raise SlugDerivationError(
                f"category={category!r} requires URL_DERIVED slug but URL "
                f"is missing/unusable (url={url!r}). Title fallback is "
                f"forbidden for this category to prevent collision-bait."
            )
        return slug

    if policy == SlugPolicy.TITLE_DERIVED:
        slug = _slug_from_title(title or "")
        if not slug:
            raise SlugDerivationError(
                f"category={category!r} requires TITLE_DERIVED slug but "
                f"title is missing or is collision-bait (title={title!r})."
            )
        return slug

    # URL_PREFERRED: try URL, fall back to title.
    slug = _slug_from_url(url or "")
    if slug:
        return slug
    slug = _slug_from_title(title or "")
    if slug:
        return slug
    raise SlugDerivationError(
        f"category={category!r}: neither URL nor title yielded a usable "
        f"slug (url={url!r}, title={title!r})."
    )


def is_collision_bait(slug: str) -> bool:
    """Check if a given slug is in the known-bad set. Used by lint #39
    and by writers in defense-in-depth mode."""
    return slug in _COLLISION_BAIT_SLUGS


# ─── Self-test ───────────────────────────────────────────────────────


if __name__ == "__main__":
    cases: list[tuple[str, str | None, str | None, str | None]] = [
        # (category, url, title, expected_slug or None for "should raise")
        ("repos", "https://github.com/anthropics/skills", None,
         "github-com-anthropics-skills"),
        ("webpages",
         "https://x.com/regent0x_/status/2049499354323399002?s=12",
         "Tweet",
         "x-com-regent0x-status-2049499354323399002"),
        ("webpages",
         "https://www.linkedin.com/posts/brijpandeyji_millions-of-people-7455470610769485824-tF2k/?utm_source=foo",
         "Post | LinkedIn",
         "linkedin-com-posts-brijpandeyji-millions-of-people-7455470610769485824-tf2k"),
        ("books", None, "Introduction to Measure Theory",
         "introduction-to-measure-theory"),
        ("papers", "https://arxiv.org/abs/2405.21060v3", None,
         "arxiv-org-abs-2405-21060"),
        # Should raise: webpages requires URL, none given
        ("webpages", None, "Some Title", None),
        # Should raise: books requires title, only URL given
        ("books", "https://example.com/book", None, None),
        # Should raise: title is collision-bait under TITLE_DERIVED
        ("books", None, "Untitled", None),
    ]

    failed = 0
    for category, url, title, expected in cases:
        try:
            slug = derive_slug(category, url, title)
            if expected is None:
                print(f"FAIL: expected raise, got {slug!r} for "
                      f"({category!r}, {url!r}, {title!r})")
                failed += 1
            elif slug != expected:
                print(f"FAIL slug:\n  in:  ({category!r}, {url!r}, {title!r})"
                      f"\n  out: {slug!r}\n  exp: {expected!r}")
                failed += 1
        except SlugDerivationError as e:
            if expected is not None:
                print(f"FAIL unexpected raise: {e}")
                failed += 1

    if failed:
        print(f"\n{failed} failures out of {len(cases)} cases")
        raise SystemExit(1)
    print(f"All {len(cases)} slug cases passed.")
